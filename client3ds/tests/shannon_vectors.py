"""Regenerate tests/shannon_vectors.h from the reference Shannon.

    python3 client3ds/tests/shannon_vectors.py path/to/shannon_ref.py

`shannon_ref.py` is a transcription of the MIT `shannon` Rust crate that
librespot interoperates with; it is not kept in this tree. The vectors it
produces are, so the C port can be checked without it.

Keys here are fixed and arbitrary -- nothing derived from a real session.
"""
import importlib.util
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / "shannon_vectors.h"

KEY_A = bytes(range(32))
KEY_B = bytes((i * 7 + 3) & 0xFF for i in range(32))


def load(path):
    spec = importlib.util.spec_from_file_location("shannon_ref", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.Shannon


def carr(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[] = {{ {body} }};\n"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    Shannon = load(sys.argv[1])
    out = ["/* Generated by shannon_vectors.py -- do not edit. */\n",
           "#ifndef SHANNON_VECTORS_H\n#define SHANNON_VECTORS_H\n",
           "#include <stdint.h>\n\n",
           carr("VEC_KEY_A", KEY_A), carr("VEC_KEY_B", KEY_B), "\n"]

    # One 32-byte block, then the MAC: the plain case.
    s = Shannon(KEY_A)
    s.nonce_u32(0)
    out.append(carr("VEC_A_CIPHER", s.encrypt(bytes(range(32)))))
    out.append(carr("VEC_A_MAC", s.finish(4)))
    out.append("\n")

    # A 3-byte header then a 5-byte body, which is the shape the access point
    # actually sends: it leaves a word part-buffered across two calls, and that
    # carry is the easiest thing in Shannon to get wrong.
    s = Shannon(KEY_B)
    s.nonce_u32(7)
    out.append(carr("VEC_B_HEADER", s.encrypt(b"\xab\x01\x02")))
    out.append(carr("VEC_B_BODY", s.encrypt(b"hello")))
    out.append(carr("VEC_B_MAC", s.finish(4)))
    out.append("\n")

    # Several packets on one cipher, with the nonce advancing as the codec does.
    s = Shannon(KEY_A)
    for n in range(3):
        s.nonce_u32(n)
        out.append(carr(f"VEC_C_PKT{n}", s.encrypt(bytes([n]) * 11)))
        out.append(carr(f"VEC_C_MAC{n}", s.finish(4)))
    out.append("\n#endif\n")

    OUT.write_text("".join(out))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
